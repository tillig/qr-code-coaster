export interface Icon {
  id: string;
  label: string;
  path: string;
  group: 'general' | 'brand';
}

const general = (id: string, label: string, path: string): Icon => ({ id, label, path, group: 'general' });
const brand = (icon: SimpleIcon): Icon => ({ id: icon.slug, label: icon.title, path: icon.path, group: 'brand' });

