export function findIcon(id: string): Icon | undefined {
  return ICONS.find((icon) => icon.id === id);
}

export function iconArt(icon: Icon): LogoArt | null {
  return artFromItems([{ color: '#000000', commands: svgPathToCommands(icon.path) }]);
}
